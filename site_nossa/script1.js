function getProgramacaoHoje() {
    const dias = ['domingo', 'segunda', 'terca', 'quarta', 'quinta', 'sexta', 'sabado'];
    const hoje = dias[new Date().getDay()];
    return programacaoSemanal[hoje];
}

function atualizarProgramacao() {
    const programacao = getProgramacaoHoje();
    const agora = new Date();
    const minAtual = agora.getHours() * 60 + agora.getMinutes();
    
    let indexAtual = programacao.findIndex(p => {
        const [hIni, mIni] = p.inicio.split(':').map(Number);
        const [hFim, mFim] = p.fim === "00:00" ? [24, 0] : p.fim.split(':').map(Number);
        return minAtual >= (hIni * 60 + mIni) && minAtual < (hFim * 60 + mFim);
    });

    if (indexAtual === -1) indexAtual = 0;
    const atual = programacao[indexAtual];
    const anterior = programacao[indexAtual === 0 ? programacao.length - 1 : indexAtual - 1];
    const proximo = programacao[indexAtual === programacao.length - 1 ? 0 : indexAtual + 1];

    const topTime = document.getElementById('programa-horario');
    const topLocutorName = document.getElementById('dj-name-mini');
    const topProgramName = document.getElementById('programa-mini');
    const topLocutorImg = document.getElementById('dj-image-mini');
    
    if (topTime) topTime.textContent = `${atual.inicio} - ${atual.fim}`;
    if (topLocutorName) topLocutorName.textContent = atual.locutor;
    if (topProgramName) topProgramName.textContent = atual.programa;
    if (topLocutorImg) topLocutorImg.src = atual.img;

    const currentTimeRange = document.getElementById('current-time-range');
    const currentName = document.getElementById('current-name');
    const currentProgram = document.getElementById('current-program');
    const currentImg = document.getElementById('current-img');
    
    if (currentTimeRange) currentTimeRange.textContent = `${atual.inicio} - ${atual.fim}`;
    if (currentName) currentName.textContent = atual.locutor;
    if (currentProgram) currentProgram.textContent = atual.programa;
    if (currentImg) currentImg.src = atual.img;

    const prevTime = document.getElementById('prev-time');
    const prevName = document.getElementById('prev-name');
    const prevProgram = document.getElementById('prev-program');
    const prevImg = document.getElementById('prev-img');
    
    if (prevTime) prevTime.textContent = `${anterior.inicio} - ${anterior.fim}`;
    if (prevName) prevName.textContent = anterior.locutor;
    if (prevProgram) prevProgram.textContent = anterior.programa;
    if (prevImg) prevImg.src = anterior.img;


    const nextTime = document.getElementById('next-time');
    const nextName = document.getElementById('next-name');
    const nextProgram = document.getElementById('next-program');
    const nextImg = document.getElementById('next-img');
    
    if (nextTime) nextTime.textContent = `${proximo.inicio} - ${proximo.fim}`;
    if (nextName) nextName.textContent = proximo.locutor;
    if (nextProgram) nextProgram.textContent = proximo.programa;
    if (nextImg) nextImg.src = proximo.img;
}
function initCarousel() {
    const track = document.getElementById('prize-track');
    if (!track) return;
    const slides = Array.from(track.children);
    let currentSlide = 0;
    const moveToSlide = (index) => {
        if (index < 0) index = slides.length - 1;
        if (index >= slides.length) index = 0;
        track.style.transform = `translateX(-${index * 100}%)`;
        currentSlide = index;
    };

}

document.addEventListener('DOMContentLoaded', () => {
    atualizarProgramacao();
    setInterval(atualizarProgramacao, 60000);
    initCarousel();

    const onAirPlayBtn = document.getElementById('on-air-play-btn');
    const mainPlayBtn = document.getElementById('main-play-btn');
    if (onAirPlayBtn && mainPlayBtn) {
        onAirPlayBtn.addEventListener('click', () => {
            if (window.miniPlayer) {
                window.miniPlayer.togglePlay();
            }
        });
    }
});
